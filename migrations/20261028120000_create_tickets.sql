CREATE TABLE tickets (
    id                  uuid        PRIMARY KEY,
    subject             text        NOT NULL,
    body                text        NOT NULL,
    status              text        NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'classified', 'needs_human')),
    status_reason       text
        CHECK (status_reason IN ('low_confidence', 'category_other', 'classifier_unavailable',
                                 'invalid_answer', 'budget_exhausted')),
    access_token_hash   bytea       NOT NULL CHECK (octet_length(access_token_hash) = 32),
    category            text,
    category_confidence real        CHECK (category_confidence BETWEEN 0 AND 1),
    complaint_p         real        CHECK (complaint_p BETWEEN 0 AND 1),
    is_complaint        boolean,
    complaint_uncertain boolean     NOT NULL DEFAULT false,
    urgency             real        CHECK (urgency BETWEEN 0 AND 3),
    urgency_confidence  real        CHECK (urgency_confidence BETWEEN 0 AND 1),
    priority            text        CHECK (priority IN ('low', 'normal', 'high', 'critical')),
    attempts            integer     NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    last_error          text,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    classified_at       timestamptz,
    -- A reason explains exactly the needs_human outcome and nothing else.
    CONSTRAINT tickets_status_reason_matches_status
        CHECK ((status = 'needs_human') = (status_reason IS NOT NULL))
);

-- Serves the pending-cap count (index-only scan on status = 'pending') and
-- operator queries by status ordered by age.
CREATE INDEX tickets_status_created_at_idx ON tickets (status, created_at);

COMMENT ON TABLE tickets IS
    'Submitted support tickets and their current triage result. subject and body are customer text: never log them or put them on Kafka.';
COMMENT ON COLUMN tickets.id IS 'UUIDv7 generated by the application; not a secret.';
COMMENT ON COLUMN tickets.status IS 'pending -> classified | needs_human; the worker only moves tickets out of pending.';
COMMENT ON COLUMN tickets.status_reason IS 'Why the ticket went to needs_human; NULL otherwise.';
COMMENT ON COLUMN tickets.access_token_hash IS 'sha256 of the one-time access token; the token itself is never stored.';
COMMENT ON COLUMN tickets.complaint_p IS 'P(yes) of the is_complaint question.';
COMMENT ON COLUMN tickets.complaint_uncertain IS 'complaint_p fell inside the configured uncertain band.';
COMMENT ON COLUMN tickets.urgency IS 'Weighted urgency score, 0 (low) to 3 (critical).';
COMMENT ON COLUMN tickets.priority IS 'urgency rounded to the nearest level.';
COMMENT ON COLUMN tickets.attempts IS 'Classifier attempts so far, for diagnostics.';
COMMENT ON COLUMN tickets.last_error IS 'Last classifier error, for diagnostics; never contains ticket text.';
COMMENT ON COLUMN tickets.classified_at IS 'When the triage result was written; NULL while pending.';

